// Swap partner keys are not in the source. They come from the environment (GitHub Actions secrets)
// or from the untracked .swap-keys.json on a developer's machine. No key just means that service is off.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
let local = {};
try { local = JSON.parse(fs.readFileSync(path.join(root, '.swap-keys.json'), 'utf8')); } catch { /* none here */ }
const keys = {
  simpleswap: process.env.SIMPLESWAP_KEY || local.simpleswap || '',
  ghostswap: process.env.GHOSTSWAP_KEY || local.ghostswap || '',
  etzswapKey: process.env.ETZSWAP_KEY || local.etzswapPublic || '',
  etzswapSecret: process.env.ETZSWAP_SECRET || local.etzswapPrivate || '',
  // ETZ counts up each time the key is regenerated, and refuses the old number.
  etzswapVersion: process.env.ETZSWAP_KEY_VERSION || String(local.etzswapVersion || '1'),
  ccecashKey: process.env.CCECASH_KEY || local.ccecashKey || '',
  changenow: process.env.CHANGENOW_KEY || local.changenow || '',
  uniswap: process.env.UNISWAP_KEY || local.uniswap || '',
  // CoinMarketCap price API key: one more price source, asked only when the others leave coins unpriced.
  coinmarketcap: process.env.CMC_KEY || local.coinmarketcap || '',
  // WalletConnect (Reown) project ID. Not a secret, but kept out of the source like the rest.
  ccecashSecret: process.env.CCECASH_SECRET || local.ccecashSecret || '',
  ccecashRefCode: process.env.CCECASH_REF_CODE || local.ccecashRefCode || '',
};
// No key appears as text in the app: each is stored masked with fresh random bytes (new on every build), split into
// pieces kept apart, and put back together only when the app runs. This makes keys harder to find in the app's files;
// it can't make them impossible to find, so the real protection stays rotating keys and the services' own limits.
const crypto = require('node:crypto');
const names = Object.keys(keys);
const masked = names.map((name) => {
  const plain = Buffer.from(keys[name], 'utf8');
  const mask = crypto.randomBytes(plain.length);
  const data = Buffer.from(plain.map((b, i) => b ^ mask[i]));
  const cut = Math.floor(data.length / 2);
  return { name, a: data.subarray(0, cut).toString('base64'), b: data.subarray(cut).toString('base64'), m: mask.toString('base64') };
});
const order = names.map((_, i) => i).sort(() => crypto.randomInt(3) - 1);
const out = `// Generated by scripts/gen-keys.js. Never commit this file.
const P = ${JSON.stringify(order.map((i) => masked[i].a))};
const Q = ${JSON.stringify(order.map((i) => masked[i].m))};
const R = ${JSON.stringify(order.map((i) => masked[i].b))};
const N = ${JSON.stringify(order.map((i) => masked[i].name.split('').reverse().join('')))};
function open(i: number): string {
  const d = Buffer.concat([Buffer.from(P[i], 'base64'), Buffer.from(R[i], 'base64')]);
  const m = Buffer.from(Q[i], 'base64');
  return Buffer.from(d.map((b, j) => b ^ m[j])).toString('utf8');
}
export const BUILTIN_SWAP_KEYS: Record<string, string> = Object.fromEntries(N.map((n, i) => [n.split('').reverse().join(''), open(i)]));
`;
fs.writeFileSync(path.join(root, 'src/main/swap-keys.generated.ts'), out);
